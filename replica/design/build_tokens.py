"""Generate CSS variables and an optional Tailwind mapping from local design tokens."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parent
t=json.loads((ROOT/'tokens.json').read_text());lines=['/* Generated by build_tokens.py; edit tokens.json. */',':root {']
for group in ('color','font','radius','shadow','motion','layout'):
 for name,value in t[group].items():lines.append(f'  --tr-{group}-{name}: {value}{"px" if isinstance(value,(int,float)) else ""};')
for value in t['space']:lines.append(f'  --tr-space-{value}: {value}px;')
for name,style in t['type'].items():
 for key,value in style.items():lines.append(f'  --tr-type-{name}-{key}: {value}{"px" if key in ("size","line") else ""};')
lines+=['}',''];(ROOT/'tokens.css').write_text('\n'.join(lines))
application=ROOT.parents[1]/'aulalocale'/'web'/'tokens.css'
if application.parent.is_dir():application.write_text('\n'.join(lines))
colors={k:f'var(--tr-color-{k})' for k in t['color']};colors['muted']=colors['text-muted']
mapping={'content':['./replica/design/*.{html,js}'],'theme':{'extend':{'colors':colors,'fontFamily':{k:[f'var(--tr-font-{k})'] for k in t['font']},'spacing':{str(n):f'var(--tr-space-{n})' for n in t['space']},'borderRadius':{k:f'var(--tr-radius-{k})' for k in t['radius']},'boxShadow':{k:f'var(--tr-shadow-{k})' for k in t['shadow']},'fontSize':{k:[f'var(--tr-type-{k}-size)',{'lineHeight':f'var(--tr-type-{k}-line)','fontWeight':str(v['weight'])}] for k,v in t['type'].items()}}}}
(ROOT/'tailwind.config.cjs').write_text('// Optional Tailwind 3 mapping; Traccia itself keeps plain CSS.\nmodule.exports = '+json.dumps(mapping,indent=2)+';\n')
